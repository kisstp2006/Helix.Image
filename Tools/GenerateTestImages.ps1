# Writes test images with the Windows imaging codecs (GDI+) and the pixels Windows decodes from them, as
# Tests/Generated/TestImages.h. Run with Windows PowerShell from the repository root:
#   powershell -ExecutionPolicy Bypass -File Tools/GenerateTestImages.ps1

Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'

$width = 37
$height = 23
$root = Split-Path -Parent $PSScriptRoot
$work = Join-Path ([System.IO.Path]::GetTempPath()) 'helix_test_images'
New-Item -ItemType Directory -Force $work | Out-Null

function New-Pattern {
    $bitmap = New-Object System.Drawing.Bitmap($width, $height, [System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    for ($y = 0; $y -lt $height; $y++) {
        for ($x = 0; $x -lt $width; $x++) {
            $color = [System.Drawing.Color]::FromArgb(255, ($x * 6) % 256, ($y * 10) % 256, (96 + $x + $y) % 256)
            $bitmap.SetPixel($x, $y, $color)
        }
    }
    return $bitmap
}

function Get-Encoder($mime) {
    return [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq $mime }
}

function Save-Image($bitmap, $path, $mime, $parameters) {
    $bitmap.Save($path, (Get-Encoder $mime), $parameters)
}

function Read-Rgba($path) {
    $image = [System.Drawing.Image]::FromFile($path)
    $copy = New-Object System.Drawing.Bitmap($image)
    $bytes = New-Object byte[] ($width * $height * 4)
    $i = 0
    for ($y = 0; $y -lt $height; $y++) {
        for ($x = 0; $x -lt $width; $x++) {
            $c = $copy.GetPixel($x, $y)
            $bytes[$i] = $c.R; $bytes[$i + 1] = $c.G; $bytes[$i + 2] = $c.B; $bytes[$i + 3] = $c.A
            $i += 4
        }
    }
    $copy.Dispose()
    $image.Dispose()
    return $bytes
}

function Format-Bytes($bytes) {
    $lines = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $bytes.Length; $i += 24) {
        $end = [Math]::Min($i + 24, $bytes.Length)
        $lines.Add('        ' + (($bytes[$i..($end - 1)] | ForEach-Object { $_.ToString() }) -join ',') + ',')
    }
    return $lines -join "`n"
}

$images = @()
$pattern = New-Pattern

$quality = New-Object System.Drawing.Imaging.EncoderParameters(1)
$quality.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter([System.Drawing.Imaging.Encoder]::Quality, [long]95)
$images += @{ name = 'Jpeg'; ext = 'jpg'; mime = 'image/jpeg'; params = $quality; tolerance = 12 }

$lzw = New-Object System.Drawing.Imaging.EncoderParameters(1)
$lzw.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter([System.Drawing.Imaging.Encoder]::Compression, [long][System.Drawing.Imaging.EncoderValue]::CompressionLZW)
$images += @{ name = 'TiffLzw'; ext = 'tif'; mime = 'image/tiff'; params = $lzw; tolerance = 0 }

$images += @{ name = 'Gif'; ext = 'gif'; mime = 'image/gif'; params = $null; tolerance = 0 }
$images += @{ name = 'Bmp'; ext = 'bmp'; mime = 'image/bmp'; params = $null; tolerance = 0 }

$out = New-Object System.Collections.Generic.List[string]
$out.Add('#pragma once')
$out.Add('')
$out.Add('// Generated by Tools/GenerateTestImages.ps1: files written by the Windows imaging codecs and the RGBA pixels')
$out.Add('// Windows decodes from them. Do not edit.')
$out.Add('')
$out.Add('namespace helix::image::testing')
$out.Add('{')
foreach ($image in $images) {
    $path = Join-Path $work ($image.name + '.' + $image.ext)
    Save-Image $pattern $path $image.mime $image.params
    $file = [System.IO.File]::ReadAllBytes($path)
    $rgba = Read-Rgba $path
    $out.Add('    inline const unsigned char k' + $image.name + 'File[] = {')
    $out.Add((Format-Bytes $file))
    $out.Add('    };')
    $out.Add('    inline const unsigned char k' + $image.name + 'Rgba[] = {')
    $out.Add((Format-Bytes $rgba))
    $out.Add('    };')
}
$out.Add('')
$out.Add('    struct TestImage')
$out.Add('    {')
$out.Add('        const char* name;')
$out.Add('        const char* extension;')
$out.Add('        const unsigned char* file;')
$out.Add('        unsigned long long fileSize;')
$out.Add('        const unsigned char* rgba;')
$out.Add('        unsigned width, height;')
$out.Add('        // Largest difference per channel from the Windows decode (lossy formats decode differently).')
$out.Add('        unsigned tolerance;')
$out.Add('    };')
$out.Add('')
$out.Add('    inline const TestImage kTestImages[] = {')
foreach ($image in $images) {
    $out.Add('        {"' + $image.name + '", "' + $image.ext + '", k' + $image.name + 'File, sizeof(k' + $image.name + 'File), k' + $image.name + 'Rgba, ' + $width + ', ' + $height + ', ' + $image.tolerance + '},')
}
$out.Add('    };')
$out.Add('}')

$target = Join-Path $root 'Tests/Generated/TestImages.h'
New-Item -ItemType Directory -Force (Split-Path -Parent $target) | Out-Null
[System.IO.File]::WriteAllText($target, ($out -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
$pattern.Dispose()
Write-Output "wrote $target"
